CREATE TABLE tarefa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    criador_id BIGINT NOT NULL,
    disciplina_id BIGINT NULL,
    tipo VARCHAR(16) NOT NULL,
    titulo VARCHAR(160) NOT NULL,
    descricao TEXT NULL,
    prazo DATE NOT NULL,
    prioridade VARCHAR(8) NOT NULL DEFAULT 'MEDIA',
    estado VARCHAR(12) NOT NULL DEFAULT 'ABERTA',
    criada_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizada_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_tarefa_criador
        FOREIGN KEY (criador_id) REFERENCES usuario (id) ON DELETE RESTRICT,
    CONSTRAINT fk_tarefa_disciplina_criador
        FOREIGN KEY (disciplina_id, criador_id)
        REFERENCES disciplina (id, usuario_id) ON DELETE RESTRICT,
    CONSTRAINT ck_tarefa_tipo
        CHECK (tipo IN ('INDIVIDUAL', 'COMPARTILHADA')),
    CONSTRAINT ck_tarefa_titulo_nao_vazio
        CHECK (length(btrim(titulo)) > 0),
    CONSTRAINT ck_tarefa_prioridade
        CHECK (prioridade IN ('BAIXA', 'MEDIA', 'ALTA')),
    CONSTRAINT ck_tarefa_estado
        CHECK (estado IN ('ABERTA', 'CONCLUIDA'))
);

CREATE INDEX idx_tarefa_criador_prazo
    ON tarefa (criador_id, prazo);

CREATE INDEX idx_tarefa_disciplina_criador
    ON tarefa (disciplina_id, criador_id);
