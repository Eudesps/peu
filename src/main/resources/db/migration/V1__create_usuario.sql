CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_usuario_nome_nao_vazio
        CHECK (length(btrim(nome)) > 0),
    CONSTRAINT ck_usuario_email_nao_vazio
        CHECK (length(btrim(email)) > 0),
    CONSTRAINT ck_usuario_senha_hash_nao_vazio
        CHECK (length(btrim(senha_hash)) > 0)
);

CREATE UNIQUE INDEX uq_usuario_email_normalizado
    ON usuario (lower(btrim(email)));
