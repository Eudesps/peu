CREATE TABLE convite_tarefa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tarefa_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL,
    estado VARCHAR(12) NOT NULL DEFAULT 'PENDENTE',
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    respondido_em TIMESTAMPTZ NULL,
    CONSTRAINT fk_convite_tarefa_tarefa
        FOREIGN KEY (tarefa_id) REFERENCES tarefa (id) ON DELETE CASCADE,
    CONSTRAINT fk_convite_tarefa_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE RESTRICT,
    CONSTRAINT ck_convite_tarefa_estado
        CHECK (estado IN ('PENDENTE', 'ACEITO', 'RECUSADO', 'CANCELADO')),
    CONSTRAINT ck_convite_tarefa_resposta
        CHECK (
            (estado = 'PENDENTE' AND respondido_em IS NULL)
            OR (estado <> 'PENDENTE' AND respondido_em IS NOT NULL)
        )
);

CREATE UNIQUE INDEX uq_convite_tarefa_pendente
    ON convite_tarefa (tarefa_id, usuario_id)
    WHERE estado = 'PENDENTE';

CREATE INDEX idx_convite_tarefa_usuario_criado
    ON convite_tarefa (usuario_id, criado_em DESC);
